//! `cargo xtask paper fetch` and the generated `paper/fetch-datasets.sh`.
use std::path::{Path, PathBuf};

use crate::diff::workspace_root;
use anyhow::{Context, Result, bail};

use crate::bench::{
    Catalog, Dataset, bench_cache_dir, derived_command, ensure_dataset, ensure_derived, input_path,
};

/// Where the generated script is committed, relative to the repository.
pub const SCRIPT_PATH: &str = "paper/fetch-datasets.sh";

pub fn load_catalog() -> Result<Catalog> {
    let text = std::fs::read_to_string(workspace_root().join("xtask/bench/datasets.toml"))
        .context("reading datasets.toml")?;
    Catalog::parse(&text)
}

pub struct FetchArgs {
    pub record: bool,
    pub only: Option<String>,
    pub image: Option<String>,
    pub data_dir: PathBuf,
}

/// Fetch every paper dataset and build every derived input.
pub fn run(a: &FetchArgs) -> Result<bool> {
    let cat = load_catalog()?;
    let cache = bench_cache_dir(&a.data_dir);
    let want = |n: &str| a.only.as_deref().is_none_or(|o| o == n);
    let known = cat.datasets.iter().any(|d| d.paper && want(&d.name))
        || cat.derived.iter().any(|d| want(&d.name));
    if !known {
        bail!(
            "--only {}: no paper dataset or derived input has that name (see xtask/bench/datasets.toml)",
            a.only.as_deref().unwrap_or("")
        );
    }
    for d in cat.datasets.iter().filter(|d| d.paper && want(&d.name)) {
        let p = ensure_dataset(d, &cache)?;
        eprintln!("{}: {}", d.name, p.display());
    }
    for d in cat.derived.iter().filter(|d| want(&d.name)) {
        let p = ensure_derived(&cat, d, &cache, a.image.as_deref(), a.record)?;
        eprintln!("{}: {}", d.name, p.display());
    }
    Ok(true)
}

/// Pins of the bench image, as comment lines: `name=version` from its
/// conda install step.
fn tool_pins(dockerfile: &str) -> Vec<String> {
    dockerfile
        .lines()
        .map(str::trim)
        .map(|l| l.trim_end_matches('\\').trim())
        .filter(|l| {
            let mut it = l.splitn(2, '=');
            let (n, v) = (it.next().unwrap_or(""), it.next().unwrap_or(""));
            !n.is_empty()
                && !v.is_empty()
                && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
                && v.starts_with(|c: char| c.is_ascii_digit())
                && !v.contains(['=', ' ', '/'])
        })
        .map(String::from)
        .collect()
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The POSIX sh script that fetches and derives everything.
pub fn generate_script(cat: &Catalog, bench_dockerfile: &str) -> Result<String> {
    let mut s = String::new();
    s.push_str(
        "#!/bin/sh\n\
         # Generated by `cargo xtask paper fetch-script` from xtask/bench/datasets.toml.\n\
         # Do not edit: change datasets.toml and regenerate.\n\
         #\n\
         # Fetches the paper datasets (D95) and builds the derived inputs. CI never\n\
         # runs this. Usage: sh paper/fetch-datasets.sh [NAME]   (NAME: one item)\n\
         # GLOCI_BENCH_CACHE sets the cache (default target/bench-data/cache).\n\
         #\n\
         # Tools the derived inputs need, as pinned in xtask/docker/Dockerfile.bench\n\
         # (run this in that image, or install the same versions):\n",
    );
    for p in tool_pins(bench_dockerfile) {
        s.push_str(&format!("#   {p}\n"));
    }
    s.push_str(
        "# Derived commands run with LC_ALL=C under plain sh (no pipefail): a\n\
         # truncated pipeline is caught by the sha256 check once it is pinned.\n\
         set -eu\n\
         ROOT=$(cd \"$(dirname \"$0\")/..\" && pwd)\n\
         CACHE=${GLOCI_BENCH_CACHE:-$ROOT/target/bench-data/cache}\n\
         ONLY=${1:-}\n\
         mkdir -p \"$CACHE\"\n\
         \n\
         want() { [ -z \"$ONLY\" ] || [ \"$ONLY\" = \"$1\" ]; }\n\
         md5_of() { if command -v md5sum >/dev/null 2>&1; then md5sum \"$1\" | cut -d' ' -f1; else md5 -q \"$1\"; fi; }\n\
         sha256_of() { if command -v sha256sum >/dev/null 2>&1; then sha256sum \"$1\" | cut -d' ' -f1; else shasum -a 256 \"$1\" | cut -d' ' -f1; fi; }\n\
         \n\
         # fetch NAME URL FILE MD5: the provider's md5 is the check.\n\
         fetch() {\n\
         \x20 want \"$1\" || return 0\n\
         \x20 if [ ! -e \"$CACHE/$3\" ]; then\n\
         \x20   echo \"fetching $1\" >&2\n\
         \x20   curl -fsSL -o \"$CACHE/$3.tmp\" \"$2\"\n\
         \x20   mv \"$CACHE/$3.tmp\" \"$CACHE/$3\"\n\
         \x20 fi\n\
         \x20 got=$(md5_of \"$CACHE/$3\")\n\
         \x20 if [ \"$got\" != \"$4\" ]; then\n\
         \x20   echo \"md5 mismatch for $1: expected $4, got $got; delete $CACHE/$3 and run again\" >&2\n\
         \x20   exit 1\n\
         \x20 fi\n\
         }\n\
         \n\
         # derive NAME SHA256 COMMAND: COMMAND sees IN, IN2... and OUT.\n\
         derive() {\n\
         \x20 want \"$1\" || return 0\n\
         \x20 if [ ! -e \"$CACHE/$1\" ]; then\n\
         \x20   echo \"deriving $1\" >&2\n\
         \x20   OUT=\"$CACHE/$1.partial\" LC_ALL=C sh -c \"$3\"\n\
         \x20   mv \"$CACHE/$1.partial\" \"$CACHE/$1\"\n\
         \x20   for f in \"$CACHE/$1.partial\".*; do\n\
         \x20     if [ -e \"$f\" ]; then mv \"$f\" \"$CACHE/$1.${f##*.partial.}\"; fi\n\
         \x20   done\n\
         \x20 fi\n\
         \x20 if [ -z \"$2\" ]; then\n\
         \x20   echo \"TO-PIN: $1 has no sha256 in datasets.toml (got $(sha256_of \"$CACHE/$1\"))\" >&2\n\
         \x20 elif [ \"$(sha256_of \"$CACHE/$1\")\" != \"$2\" ]; then\n\
         \x20   echo \"sha256 mismatch for $1: expected $2; delete $CACHE/$1 and run again\" >&2\n\
         \x20   exit 1\n\
         \x20 fi\n\
         }\n\n",
    );
    for d in cat.datasets.iter().filter(|d| d.paper) {
        s.push_str(&fetch_line(d)?);
    }
    s.push('\n');
    for d in &cat.derived {
        let mut ins = Vec::new();
        let mut exports = Vec::new();
        for (i, f) in d.from.iter().enumerate() {
            let var = if i == 0 {
                "IN".to_string()
            } else {
                format!("IN{}", i + 1)
            };
            let path = input_path(cat, f, Path::new("/CACHE"))?;
            let shell = match f.strip_prefix("repo:") {
                Some(p) => format!("$ROOT/{p}"),
                None => format!("$CACHE/{}", path.file_name().unwrap().to_string_lossy()),
            };
            exports.push(format!("{var}=\"{shell}\""));
            ins.push(format!("\"${var}\""));
        }
        let cmd = derived_command(&d.command, &ins, "\"$OUT\"");
        s.push_str(&format!(
            "export {}\nderive {} {} {}\n",
            exports.join(" "),
            sh_quote(&d.name),
            sh_quote(&d.sha256),
            sh_quote(&cmd),
        ));
    }
    Ok(s)
}

fn fetch_line(d: &Dataset) -> Result<String> {
    let (alg, hex) = d.checksum()?;
    if alg != "md5" {
        bail!(
            "paper dataset {} must use the provider's md5 (found {alg})",
            d.name
        );
    }
    let file = d.url.split('/').next_back().unwrap_or(&d.name);
    Ok(format!(
        "fetch {} {} {} {}\n",
        sh_quote(&d.name),
        sh_quote(&d.url),
        sh_quote(file),
        sh_quote(hex)
    ))
}

/// Write the script to `out` (default `paper/fetch-datasets.sh`).
pub fn write_script(out: Option<&Path>) -> Result<()> {
    let root = workspace_root();
    let script = generate_script(
        &load_catalog()?,
        &std::fs::read_to_string(root.join("xtask/docker/Dockerfile.bench"))?,
    )?;
    let path = out.map(Path::to_path_buf).unwrap_or(root.join(SCRIPT_PATH));
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p)?;
    }
    std::fs::write(&path, script)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))?;
    }
    eprintln!("wrote {}", path.display());
    Ok(())
}
