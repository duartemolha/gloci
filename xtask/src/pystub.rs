/// The type of a keyword argument, and its default (None for a required one).
fn kw_type(k: &Kw) -> (String, Option<&'static str>) {
    let a = k.arg;
    let base = if !a.takes_value {
        return ("bool".into(), Some("False"));
    } else if a.takes_file {
        if a.multiple {
            format!("{SOURCE} | Sequence[{SOURCE}]")
        } else {
            SOURCE.into()
        }
    } else if !a.possible_values.is_empty() {
        let lit = format!(
            "Literal[{}]",
            a.possible_values
                .iter()
                .map(|v| quote(v))
                .collect::<Vec<_>>()
                .join(", ")
        );
        if a.multiple {
            format!("{lit} | Sequence[{lit}]")
        } else {
            lit
        }
    } else if a.multiple {
        format!("{VALUE} | Sequence[{VALUE}]")
    } else {
        VALUE.into()
    };
    if k.required {
        (base, None)
    } else {
        (format!("{base} | None"), Some("None"))
    }
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// `text` as the body of a docstring at `indent` spaces: lines of it indented, and escaped
/// where a quote or backslash would end or change the string.
fn doc_body(text: &str, indent: usize) -> String {
    let pad = " ".repeat(indent);
    let escaped = text.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    let mut out = String::new();
    for line in escaped.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "{pad}{line}");
        }
    }
    let mut out = out.trim_end().to_string();
    if out.ends_with('"') {
        out.pop();
        out.push_str("\\\"");
    }
    out
}

/// A docstring: the about text, `Args:` with each argument's help, and the `CLI:` line. The
/// runtime builds the same text (`gloci._signature.make_doc`).
pub fn docstring(about: &str, args: &[(String, String)], skipped: &[Skipped], cli: &str) -> String {
    let mut s = squash(about);
    if !args.is_empty() {
        s.push_str("\n\nArgs:");
        for (name, help) in args {
            let help = squash(help);
            if help.is_empty() {
                let _ = write!(s, "\n    {name}:");
            } else {
                let _ = write!(s, "\n    {name}: {help}");
            }
        }
    }
    if let Some(first) = skipped.first() {
        let names: Vec<&str> = skipped.iter().map(|k| k.name.as_str()).collect();
        let value = if first.switch { "True" } else { "\"...\"" };
        let _ = write!(
            s,
            "\n\nNot Python identifiers, so not parameters: {}. Pass one as **{{\"{}\": {value}}}.",
            names.join(", "),
            first.name
        );
    }
    let _ = write!(s, "\n\nCLI: {cli}");
    s
}

/// `text` on one line: runs of whitespace as one space.
fn squash(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// The documented arguments of a signature: the function's own leading ones, `out`, then the
/// keywords.
fn doc_args(sig: &Signature) -> Vec<(String, String)> {
    let mut v: Vec<(String, String)> = sig
        .lead
        .iter()
        .map(|(n, h)| (n.to_string(), h.to_string()))
        .collect();
    if let Some(h) = sig.out {
        v.push(("out".into(), h.into()));
    }
    v.extend(sig.args.iter().map(|k| {
        let help = match &k.alias_of {
            Some(long) => format!("alias of {long}"),
            None => k.arg.help.clone(),
        };
        (k.name.clone(), help)
    }));
    v
}

/// One `def`, at `indent` spaces, with its docstring.
fn def(
    name: &str,
    lead: &[String],
    star: Option<&str>,
    sig: &Signature,
    ret: &str,
    indent: usize,
) -> String {
    let pad = " ".repeat(indent);
    let inner = " ".repeat(indent + 4);
    let mut params: Vec<String> = lead.to_vec();
    match star {
        Some(s) => params.push(s.to_string()),
        None => params.push("*".into()),
    }
    if sig.out.is_some() {
        params.push("out: str | os.PathLike[str]".to_string());
    }
    for k in &sig.args {
        let (ty, default) = kw_type(k);
        params.push(match default {
            Some(d) => format!("{}: {ty} = {d}", k.name),
            None => format!("{}: {ty}", k.name),
        });
    }
    let cli = format!("gloci {}", sig.spec.path.join(" "));
    let doc = docstring(&sig.spec.about, &doc_args(sig), &sig.skipped, &cli);
    let mut s = format!("{pad}def {name}(\n");
    for p in params {
        let _ = writeln!(s, "{inner}{p},");
    }
    let _ = writeln!(s, "{pad}) -> {ret}:");
    let _ = writeln!(
        s,
        "{inner}\"\"\"{}",
        doc_body(&doc, indent + 4).trim_start()
    );
    let _ = writeln!(s, "{inner}\"\"\"");
    s
}

/// The whole stub.
pub fn render_pyi() -> Result<String> {
    let mut out = String::from(HEAD);
    out.push('\n');
    for b in BINDINGS {
        let sig = gloci::embed::step_signature(b)
            .with_context(|| format!("no spec for {}", b.path.join(" ")))?;
        // A step without extra sources has a bare `*`; one with them has `*sources`, which
        // makes the keywords keyword-only already.
        let star = sig.nary.then_some("*sources: Source");
        out.push_str(&def(
            b.method,
            &["self".to_string()],
            star,
            &sig,
            "Pipeline",
            4,
        ));
    }
    out.push('\n');
    out.push_str(OPEN);
    for (_, f) in MODULE_FUNCTIONS {
        let sig = gloci::embed::function_signature(f)
            .with_context(|| format!("no spec for function {f}"))?;
        let source = gloci::embed::SOURCES.contains(f);
        let lead: Vec<String> = sig
            .lead
            .iter()
            .map(|(n, _)| {
                format!(
                    "{n}: {}",
                    if *f == "index" {
                        "str | os.PathLike[str]"
                    } else {
                        SOURCE
                    }
                )
            })
            .collect();
        let ret = if source {
            "Pipeline"
        } else {
            "list[pathlib.Path]"
        };
        out.push('\n');
        out.push_str(&def(f, &lead, None, &sig, ret, 0));
    }
    Ok(out)
}

/// Write the stub to `out`.
pub fn generate_pyi(out: &Path) -> Result<()> {
    let text = render_pyi()?;
    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(out, text).with_context(|| format!("write {}", out.display()))
}
