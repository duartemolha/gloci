//! `cargo xtask pystub`: the Python type stub, `crates/gloci-py/python/gloci/__init__.pyi`.
//!
//! Everything about the commands is generated from the same specs the runtime reads
//! (`gloci::embed`: `BINDINGS`, `MODULE_FUNCTIONS`, `SOURCES`, `reserved`, and the signatures
//! `embed::step_signature`/`function_signature`), so the stub cannot disagree with what the
//! library accepts: the step methods, the module functions, their keyword arguments and
//! their docstrings. The classes and terminal methods that no spec describes are the two
//! templates below ([`HEAD`] and [`OPEN`]); `pyi_is_current` (xtask/tests/pystub.rs) fails
//! when the committed file is not what this makes.
//!
//! Types of a keyword argument, by what its clap definition says:
//! - a switch: `bool = False`;
//! - one that takes a file ([`gloci::embed::ArgSpec::takes_file`]): `Source` (`Source |
//!   Sequence[Source]` where it may repeat);
//! - one with possible values: `Literal[...]` (or a sequence of them where it may repeat);
//! - one that may repeat: `Value | Sequence[Value]`, `Value` being the line below;
//! - any other: `str | int | float | os.PathLike[str]` (the value is passed as `str()`).
//!
//! An argument that is not required is `| None = None`. Each one-letter short flag and visible
//! alias is a parameter too, of its long form's type, documented "alias of <long>"; an argument
//! with such names is never required in the signature (the command line's check says what is
//! missing). Names that are not Python identifiers (`--5p`) are not parameters; the docstring
//! says how to pass them.

